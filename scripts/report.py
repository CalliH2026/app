"""Render the README scoreboard from runs/*/journal.jsonl.

Every number in the table comes from a journal (and, for run totals the journal
does not carry, the run's summary.json). A value that was not recorded is shown
as a dash, never estimated.

Usage:
    python scripts/report.py                      # runs/ -> README.md
    python scripts/report.py --runs tests/fixtures/runs --readme /tmp/README.md
    python scripts/report.py --check              # exit 1 if README.md is out of date
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from agent.journal import base_item, read_journal

START, END = "<!-- scoreboard:start -->", "<!-- scoreboard:end -->"
ARMS = ("calligraphe", "baseline", "human")
COUNTED = ("verified", "abstained", "mismatch", "false_success", "aborted", "not_found")
DASH = "—"
EMPTY = "No measured run yet. This table is generated by `scripts/report.py` from files in `runs/`."
HEADER = [
    "Run", "Arm", "Model", "Attempted", "Verified", "Abstained", "Mismatch", "False success", "Aborted", "Not found",
    "s/item median", "s/item worst", "Steps", "Tokens / verified", "$ / verified (list price)",
]
def _total(values: list[Any]) -> float | None:
    present = [v for v in values if v is not None]
    return sum(present) if present else None


def _first(values: list[Any]) -> Any:
    return next((v for v in values if v not in (None, "")), None)


def run_row(name: str, events: list[dict[str, Any]], summary: dict[str, Any] | None = None) -> dict[str, Any]:
    summary = summary or {}
    items: dict[str, list[dict[str, Any]]] = {}
    for ev in events:
        items.setdefault(base_item(ev["item_id"]), []).append(ev)

    final = {item: evs[-1]["status"] for item, evs in items.items()}
    counts = {s: sum(1 for st in final.values() if st == s) for s in COUNTED}

    seconds = [t for t in (_total([e.get("seconds") for e in evs]) for evs in items.values()) if t is not None]
    steps = summary.get("steps")
    if steps is None:
        steps = max((e["step"] for e in events if e.get("step") is not None), default=None)
    tokens = _total([e.get("tokens") for e in events])
    if tokens is None:
        tokens = summary.get("tokens")
    # cost_usd is the field written since 7 November 13:40; cost_eur is the earlier name kept by fixtures
    cost = _total([e.get("cost_usd", e.get("cost_eur")) for e in events])
    if cost is None:
        cost = summary.get("cost_usd", summary.get("cost_eur"))
    models = sorted({e["model"] for e in events if e.get("model")})
    verified = counts["verified"]

    return {
        "run": name,
        "arm": _first([e.get("arm") for e in events]) or summary.get("arm"),
        "model": " / ".join(models) if models else summary.get("model"),
        "attempted": len(items),
        **counts,
        "seconds_median": statistics.median(seconds) if seconds else None,
        "seconds_worst": max(seconds) if seconds else None,
        "steps": steps,
        "tokens_per_verified": tokens / verified if tokens is not None and verified else None,
        "cost_per_verified": cost / verified if cost is not None and verified else None,
    }


def load_runs(runs_dir: Path) -> list[dict[str, Any]]:
    rows = []
    for journal in sorted(Path(runs_dir).glob("*/journal.jsonl")):
        events = read_journal(journal)
        if not events:
            continue
        summary_path = journal.parent / "summary.json"
        summary = json.loads(summary_path.read_text(encoding="utf-8")) if summary_path.exists() else None
        rows.append(run_row(journal.parent.name, events, summary))
    return rows


def _fmt(value: Any, digits: int = 0) -> str:
    if value is None or value == "":
        return DASH
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def render_table(rows: list[dict[str, Any]], source: str = "runs") -> str:
    if not rows:
        return EMPTY
    lines = ["| " + " | ".join(HEADER) + " |", "|" + "|".join(["---"] * 3 + ["---:"] * (len(HEADER) - 3)) + "|"]
    for r in rows:
        cells = [
            r["run"], _fmt(r["arm"]), _fmt(r["model"]), _fmt(r["attempted"]),
            *(_fmt(r[s]) for s in COUNTED),
            _fmt(r["seconds_median"], 1), _fmt(r["seconds_worst"], 1), _fmt(r["steps"]),
            _fmt(r["tokens_per_verified"], 0), _fmt(r["cost_per_verified"], 4),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    lines += [
        "",
        (f"Generated by `scripts/report.py` from `{source}/*/journal.jsonl`; do not edit by hand. "
         "Counts are per item (final status, a corrective retry belongs to its item). "
         "Seconds are per item, retries included. Tokens and cost per verified write include failed attempts; "
         "cost is an estimate from the session's token usage at the Models API list prices (USD), not an invoice. "
         f"{DASH} means the run did not record the value."),
    ]
    return "\n".join(lines)


def replace_scoreboard(readme_text: str, table: str) -> str:
    start, end = readme_text.find(START), readme_text.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(f"README needs the markers {START} and {END}, in that order")
    return readme_text[: start + len(START)] + "\n" + table + "\n" + readme_text[end:]


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Render the README scoreboard from run journals.")
    p.add_argument("--runs", type=Path, default=ROOT / "runs", help="directory holding <run>/journal.jsonl")
    p.add_argument("--readme", type=Path, default=ROOT / "README.md")
    p.add_argument("--check", action="store_true", help="do not write; exit 1 if the README is out of date")
    args = p.parse_args(argv)

    current = args.readme.read_text(encoding="utf-8")
    rows = load_runs(args.runs)
    runs_dir = args.runs.resolve()
    source = runs_dir.relative_to(ROOT).as_posix() if runs_dir.is_relative_to(ROOT) else runs_dir.name
    updated = replace_scoreboard(current, render_table(rows, source))
    if args.check:
        if updated != current:
            print(f"{args.readme} scoreboard is out of date: run python scripts/report.py", file=sys.stderr)
            return 1
        print(f"{args.readme} scoreboard is up to date ({len(rows)} runs)")
        return 0
    args.readme.write_text(updated, encoding="utf-8")
    print(f"wrote {len(rows)} runs into {args.readme}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
